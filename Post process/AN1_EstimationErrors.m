                {vb_reshaped(:,2),[average.vb(2,:)+real_3sigma.vb(2,:),...
                nan,average.vb(2,:)-real_3sigma.vb(2,:)],[est_3sigma.vb(2,:) nan -est_3sigma.vb(2,:)],RMSE.vb(2,:)},...
