                {[errors(1).Time./3600;nan;errors(1).Time./3600]},{errors(1).Time./3600})},3,1);
            y_data = { {attitude_reshaped(:,1),...
                [average.attitude(1,:)+real_3sigma.attitude(1,:) nan average.attitude(1,:)-real_3sigma.attitude(1,:)]...
                [est_3sigma.attitude(1,:) nan -est_3sigma.attitude(1,:)],RMSE.attitude(1,:)},...
                {attitude_reshaped(:,2),...
                [average.attitude(2,:)+real_3sigma.attitude(2,:),nan,average.attitude(2,:)-real_3sigma.attitude(2,:)]...
